// Generate src/types/database.ts without Docker (owner: backend).
// Applies supabase/migrations/*.sql to PGlite, serves it on a local socket, and runs the real
// Supabase CLI generator against it: `supabase gen types typescript --remote=<url> --schema public`.
// Output is formatted with oxfmt (the formatter the CLI recommends).
//
//   npm --prefix supabase/tests ci
//   node supabase/tests/gen-types.mjs           # write src/types/database.ts
//   node supabase/tests/gen-types.mjs --check   # exit 1 if the committed file is stale (for CI)
//
// With Docker available, `supabase start && supabase gen types typescript --local --schema public`
// produces the same public schema types.
import { PGLiteSocketServer } from '@electric-sql/pglite-socket';
import { execFile, execFileSync } from 'child_process';
import { promisify } from 'util';
import fs from 'fs';
import net from 'net';
import os from 'os';
import path from 'path';
import { createDb, supabaseDir } from './pglite-supabase.mjs';

const check = process.argv.includes('--check');
const here = path.join(supabaseDir, 'tests');
const bin = name => path.join(here, 'node_modules', '.bin', name);
const target = path.join(supabaseDir, '..', 'src', 'types', 'database.ts');

const freePort = () => new Promise((resolve, reject) => {
  const s = net.createServer().listen(0, '127.0.0.1', () => { const { port } = s.address(); s.close(() => resolve(port)); });
  s.on('error', reject);
});

const db = await createDb();
const port = await freePort();
const server = new PGLiteSocketServer({ db, port, host: '127.0.0.1', maxConnections: 10 });
await server.start();

let generated;
try {
  // Async on purpose: the PGlite server runs in this process, so a sync child would deadlock.
  const { stdout: raw } = await promisify(execFile)(bin('supabase'), [
    'gen', 'types', 'typescript', '--schema', 'public',
    `--remote=postgresql://postgres:postgres@127.0.0.1:${port}/postgres?sslmode=disable`,
  ], { encoding: 'utf8', cwd: os.tmpdir(), maxBuffer: 32 * 1024 * 1024 });
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'bonded-types-'));
  const file = path.join(tmp, 'database.ts');
  fs.writeFileSync(file, raw);
  execFileSync(bin('oxfmt'), [file], { cwd: tmp, stdio: 'pipe' }); // throws with stderr on failure
  generated = '// Generated by supabase/tests/gen-types.mjs from supabase/migrations. Do not edit.\n' + fs.readFileSync(file, 'utf8');
  fs.rmSync(tmp, { recursive: true, force: true });
} finally {
  await server.stop();
  await db.close();
}

if (!generated.includes('export type Database')) { console.error('generator returned no Database type'); process.exit(1); }
if (check) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== generated) {
    console.error('src/types/database.ts is stale: run `node supabase/tests/gen-types.mjs` and commit it');
    process.exit(1);
  }
  console.log('src/types/database.ts is up to date');
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, generated);
  console.log(`wrote ${path.relative(process.cwd(), target)}`);
}
