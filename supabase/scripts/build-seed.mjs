// Build supabase/seed.sql (BE-05): content + dev seed engine + the personas from qa/fixtures/personas.json.
//
//   node supabase/scripts/build-seed.mjs           # write supabase/seed.sql
//   node supabase/scripts/build-seed.mjs --check   # exit 1 if the committed seed.sql is stale (CI)
//
// seed.sql runs on `supabase db reset` (local) and may be applied to the `dev` project. Never prod:
// its first statement refuses to run in a database that has users who are not @bonded.test personas.
// CONTENT_INCLUDE_AGE_GATED=true includes the 18+ pack (D33); the committed file is built without it.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { contentSql, includeAgeGatedFromEnv } from './content-sql.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const supabaseDir = path.join(here, '..');
const personasFile = path.join(supabaseDir, '..', 'qa', 'fixtures', 'personas.json');
const target = path.join(supabaseDir, 'seed.sql');
export const DEFAULT_SCENARIO = 'streak-11-both-answered';

const q = s => `'${String(s).replace(/'/g, "''")}'`;
const qn = s => (s == null ? 'null' : q(s));
const arr = a => `array[${a.map(q).join(', ')}]::text[]`;

export function personasSql(personas = JSON.parse(fs.readFileSync(personasFile, 'utf8'))) {
  const out = [];
  const rows = Object.entries(personas.personas).map(([key, p]) =>
    `  (${q(key)}, ${q(p.id)}::uuid, ${q(p.email)}, ${q(p.display_name)}, ${q(p.timezone)}, ${q(p.locale)}, ${qn(p.platform)})`);
  out.push(`insert into dev_seed.persona (key, id, email, display_name, timezone, locale, platform) values`, rows.join(',\n'),
    `on conflict (key) do update set id = excluded.id, email = excluded.email, display_name = excluded.display_name,
  timezone = excluded.timezone, locale = excluded.locale, platform = excluded.platform;`);
  const couples = Object.entries(personas.couples);
  out.push(`insert into dev_seed.couple (key, id, members, timezone, stage, goals, partner_name) values`,
    couples.map(([key, c]) => `  (${q(key)}, ${q(c.id)}::uuid, ${arr(c.members)}, ${q(c.timezone)}, ${qn(c.stage)}, ${arr(c.goals ?? [])}, ${qn(c.partner_name_at_invite)})`).join(',\n'),
    `on conflict (key) do update set id = excluded.id, members = excluded.members, timezone = excluded.timezone, stage = excluded.stage,
  goals = excluded.goals, partner_name = excluded.partner_name;`);
  const dates = couples.flatMap(([key, c]) => (c.key_dates ?? []).map(d => `  (${q(key)}, ${q(d.kind)}, ${qn(d.user)}, ${q(d.date)}::date)`));
  out.push(`delete from dev_seed.key_date;`);
  if (dates.length) out.push(`insert into dev_seed.key_date (couple_key, kind, user_key, date) values`, dates.join(',\n') + ';');
  return out.join('\n') + '\n';
}

export function buildSeed({ includeAgeGated = includeAgeGatedFromEnv() } = {}) {
  const guard = `-- Refuse to run next to real users: persona accounts are @bonded.test.
do $guard$
begin
  if exists (select 1 from auth.users where coalesce(email, '') not like '%@bonded.test') then
    raise exception 'seed.sql refuses to run: this database has users who are not @bonded.test personas';
  end if;
end $guard$;
`;
  return [
    `-- GENERATED by supabase/scripts/build-seed.mjs. Do not edit: change supabase/content/*.csv,`,
    `-- supabase/scripts/dev-seed.sql or qa/fixtures/personas.json and rebuild.`,
    `-- Local stack and \`dev\` only. After a reset the database is in scenario "${DEFAULT_SCENARIO}";`,
    `-- switch with: select dev_seed.apply_scenario('<id>');   (ids: select * from dev_seed.scenarios())`,
    ``, guard,
    `-- ── content (idempotent, D33) ──`, contentSql({ includeAgeGated }),
    `-- ── dev seed engine ──`, fs.readFileSync(path.join(here, 'dev-seed.sql'), 'utf8'),
    `-- ── personas (qa/fixtures/personas.json) ──`, personasSql(),
    `select dev_seed.apply_scenario('${DEFAULT_SCENARIO}');`, ``,
  ].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const sql = buildSeed();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
    if (cur !== sql) { console.error('supabase/seed.sql is stale: run `node supabase/scripts/build-seed.mjs` and commit it'); process.exit(1); }
    console.log('supabase/seed.sql is up to date');
  } else {
    fs.writeFileSync(target, sql);
    console.log(`wrote supabase/seed.sql (${sql.split('\n').length} lines)`);
  }
}
