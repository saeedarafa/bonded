#!/usr/bin/env node
// Builds the progress table at the top of docs/plan/BACKLOG.md from the Status column of every
// task table (todo / doing / done / blocked). Owner: lead architect.
// Usage: node scripts/plan/progress.mjs [--check]   (--check exits 1 if the table is stale or a status is invalid)
// A task spanning milestones ("M3–M4") counts in its last one; "all" counts as ongoing.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const FILE = 'docs/plan/BACKLOG.md';
const START = '<!-- progress:start (generated by node scripts/plan/progress.mjs; do not edit by hand) -->';
const END = '<!-- progress:end -->';
const STATUSES = ['done', 'doing', 'blocked', 'todo'];

/** Parses every markdown table whose header has ID, Status, M and Prio columns. */
export function parseTasks(md) {
  const tasks = [];
  const errors = [];
  let cols = null;
  for (const line of md.split('\n')) {
    if (!line.startsWith('|')) { cols = null; continue; }
    const cells = line.slice(1, line.endsWith('|') ? -1 : undefined).split(/(?<!\\)\|/).map((c) => c.trim());
    if (!cols) {
      const idx = Object.fromEntries(['ID', 'Status', 'M', 'Prio'].map((h) => [h, cells.indexOf(h)]));
      cols = Object.values(idx).every((i) => i >= 0) ? idx : { skip: true };
      continue;
    }
    if (cols.skip || /^-+$/.test(cells[0])) continue;
    const t = { id: cells[cols.ID], status: cells[cols.Status], m: cells[cols.M], prio: cells[cols.Prio] };
    if (!STATUSES.includes(t.status)) errors.push(`${t.id}: status "${t.status}" is not one of ${STATUSES.join(' / ')}`);
    tasks.push(t);
  }
  return { tasks, errors };
}

const milestoneOf = (m) => {
  const all = m.match(/M\d/g);
  if (all) return all[all.length - 1];
  return m === 'all' ? 'ongoing' : m || '?';
};

export function progressTable(tasks) {
  const groups = new Map();
  for (const t of tasks) {
    const k = milestoneOf(t.m);
    if (!groups.has(k)) groups.set(k, []);
    groups.get(k).push(t);
  }
  const order = (k) => (/^M\d$/.test(k) ? Number(k[1]) : k === 'later' ? 90 : 95);
  const keys = [...groups.keys()].sort((a, b) => order(a) - order(b) || a.localeCompare(b));
  const count = (list, s) => list.filter((t) => t.status === s).length;
  const isP0 = (t) => /P0/.test(t.prio);
  const row = (label, list) => {
    const p0 = list.filter(isP0);
    return `| ${label} | **${count(list, 'done')} / ${list.length}** | ${count(list, 'doing')} | ${count(list, 'blocked')} | ${count(list, 'todo')} | ${count(p0, 'done')} / ${p0.length} |`;
  };
  const lines = [
    START,
    '## Progress',
    '',
    '| Milestone | Done / total | Doing | Blocked | Todo | P0 done / total |',
    '|---|---|---|---|---|---|',
    ...keys.map((k) => row(k, groups.get(k))),
    row('**All**', tasks),
    '',
    'Counted from the Status column below (a task spanning milestones counts in its last one; `all` = ongoing lead work). The lead updates a row\'s status when its PR merges, then runs `node scripts/plan/progress.mjs`.',
    END,
  ];
  return lines.join('\n');
}

export function render(md) {
  const { tasks, errors } = parseTasks(md);
  const table = progressTable(tasks);
  const s = md.indexOf(START.slice(0, 22));
  const e = md.indexOf(END);
  let out;
  if (s >= 0 && e > s) out = md.slice(0, s) + table + md.slice(e + END.length);
  else {
    // First run: insert after the intro bullets, before the first "## " heading.
    const h = md.indexOf('\n## ');
    out = md.slice(0, h + 1) + table + '\n\n' + md.slice(h + 1);
  }
  return { out, errors, count: tasks.length };
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const abs = join(root, FILE);
  const md = readFileSync(abs, 'utf8');
  const { out, errors, count } = render(md);
  if (errors.length) { console.error(errors.join('\n')); process.exit(1); }
  if (out === md) console.log(`progress up to date (${count} tasks)`);
  else if (process.argv.includes('--check')) { console.error(`stale: ${FILE} progress table (run node scripts/plan/progress.mjs)`); process.exit(1); }
  else { writeFileSync(abs, out); console.log(`wrote ${FILE} progress table (${count} tasks)`); }
}
