#!/usr/bin/env node
// Builds docs/plan/SCOPE.md and qa/release/screen-requirements.csv from
// design-handoff/screens.json + docs/plan/scope-map.json. Fails if a screen has no scope entry.
// Also refreshes the progress table in docs/plan/BACKLOG.md from its Status column (progress.mjs).
// Usage: node scripts/plan/generate.mjs [--check]   (--check exits 1 if the outputs are stale)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { render as renderProgress } from './progress.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const read = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));
const { screens } = read('design-handoff/screens.json');
const scope = read('docs/plan/scope-map.json');

const missing = screens.filter((s) => !scope.screens[s.id]).map((s) => s.id);
const extra = Object.keys(scope.screens).filter((id) => !screens.some((s) => s.id === id));
if (missing.length || extra.length) {
  console.error(`scope-map.json out of sync. Missing: ${missing.join(', ') || '-'}; unknown: ${extra.join(', ') || '-'}`);
  process.exit(1);
}

const rows = screens.map((s) => ({ ...s, ...scope.screens[s.id] }));
const order = ['P0', 'P1', 'P2', 'phase2', 'ref'];
const cell = (v) => String(v ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const tasks = (r) => [...(r.mob || []), ...(r.be || []), ...(r.lead || [])].join(', ') || '—';

let md = `# Scope: every designed screen, prioritised\n\n`;
md += `Generated by \`node scripts/plan/generate.mjs\` from \`design-handoff/screens.json\` and \`docs/plan/scope-map.json\`. Don't edit by hand; edit the scope map (lead architect).\n\n`;
md += `**Priorities:** P0 = launch blocker · P1 = launch if on time · P2 = after launch · phase2 = AI phase · ref = reference only.\n\n`;
md += `**Milestones:** ${Object.entries(scope.milestones).map(([k, v]) => `${k} ${v}`).join(' · ')}\n\n`;
md += `| Priority | Count |\n|---|---|\n`;
for (const p of order) md += `| ${p} | ${rows.filter((r) => r.p === p).length} |\n`;
for (const p of order) {
  const group = rows.filter((r) => r.p === p).sort((a, b) => a.m.localeCompare(b.m));
  if (!group.length) continue;
  md += `\n## ${p}\n\n| ID | Screen | Lane | Milestone | Route | Tasks | Behaviour |\n|---|---|---|---|---|---|---|\n`;
  for (const r of group) md += `| ${r.id} | ${cell(r.title)} | ${r.lane} | ${r.m} | \`${cell(r.route)}\` | ${tasks(r)} | ${cell(r.notes)} |\n`;
}

const csvq = (v) => `"${String(v ?? '').replace(/"/g, '""')}"`;
const header = ['req_id', 'screen_id', 'title', 'lane', 'priority', 'milestone', 'platforms', 'requirement', 'board_file', 'verification', 'tasks'];
const lines = [header.join(',')];
for (const r of rows) {
  if (r.p === 'phase2' || r.p === 'ref') continue;
  const platforms = r.lane === 'L5' ? 'store' : r.route === 'external' ? 'messenger' : 'ios,android';
  const base = [r.id, r.title, r.lane, r.p, r.m, platforms];
  lines.push([`SCR-${r.id}-UI`, ...base, `Matches ${r.board} in light and dark: layout, copy, tokens, all states (loading, empty, error, offline).`, `design-handoff/${r.board_file}`, 'manual+screenshot', tasks(r)].map(csvq).join(','));
  if (r.notes && r.notes !== '—') lines.push([`SCR-${r.id}-BEH`, ...base, r.notes, `design-handoff/${r.board_file}`, 'e2e', tasks(r)].map(csvq).join(','));
  if (r.data && r.data !== '—') lines.push([`SCR-${r.id}-DATA`, ...base, `Data: ${r.data}`, `design-handoff/${r.board_file}`, 'contract+e2e', tasks(r)].map(csvq).join(','));
}

const progress = renderProgress(readFileSync(join(root, 'docs/plan/BACKLOG.md'), 'utf8'));
if (progress.errors.length) {
  console.error(`BACKLOG.md Status column: ${progress.errors.join('; ')}`);
  process.exit(1);
}

const outputs = {
  'docs/plan/SCOPE.md': md,
  'qa/release/screen-requirements.csv': lines.join('\n') + '\n',
  'docs/plan/BACKLOG.md': progress.out,
};
const check = process.argv.includes('--check');
let stale = false;
for (const [p, content] of Object.entries(outputs)) {
  const abs = join(root, p);
  let current = null;
  try { current = readFileSync(abs, 'utf8'); } catch {}
  if (current === content) continue;
  stale = true;
  if (!check) { mkdirSync(dirname(abs), { recursive: true }); writeFileSync(abs, content); console.log(`wrote ${p}`); }
  else console.error(`stale: ${p}`);
}
if (check && stale) process.exit(1);
if (!stale) console.log('up to date');
