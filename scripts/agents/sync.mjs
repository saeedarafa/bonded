#!/usr/bin/env node
// One source, three AI tools. Edit agents and skills ONLY in .github/, then run this.
//   .github/skills/<name>/      -> .claude/skills/<name>/   (Claude Code)
//                               -> .agents/skills/<name>/   (Codex; also read by Copilot)
//   .github/agents/*.agent.md   -> .claude/agents/<slug>.md (Claude Code sub-agent wrappers)
// Copilot reads .github/ directly. Codex gets roles through AGENTS.md.
// Usage: node scripts/agents/sync.mjs [--check]   (--check exits 1 when a copy is stale)
// Copies, not symlinks: iCloud Drive and Windows checkouts don't keep symlinks reliably.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync, rmSync, existsSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const check = process.argv.includes('--check');
const MARK = '.synced-from-github';
let stale = [];

const walk = (dir) => readdirSync(dir).flatMap((n) => {
  if (n === '.DS_Store') return [];
  const p = join(dir, n);
  return statSync(p).isDirectory() ? walk(p) : [p];
});

function put(abs, content) {
  const current = existsSync(abs) ? readFileSync(abs) : null;
  if (current && Buffer.compare(current, Buffer.from(content)) === 0) return;
  stale.push(relative(root, abs));
  if (!check) { mkdirSync(dirname(abs), { recursive: true }); writeFileSync(abs, content); }
}

// Skills
const srcSkills = join(root, '.github/skills');
const skills = readdirSync(srcSkills).filter((n) => existsSync(join(srcSkills, n, 'SKILL.md')));
for (const target of ['.claude/skills', '.agents/skills']) {
  for (const name of skills) {
    const from = join(srcSkills, name);
    const to = join(root, target, name);
    const files = walk(from);
    for (const f of files) put(join(to, relative(from, f)), readFileSync(f));
    put(join(to, MARK), `Generated by scripts/agents/sync.mjs from .github/skills/${name}. Edit the source, not this copy.\n`);
    // Remove files that no longer exist in the source (only inside synced skill folders).
    if (existsSync(to)) for (const f of walk(to)) {
      const rel = relative(to, f);
      if (rel !== MARK && !existsSync(join(from, rel))) { stale.push(relative(root, f)); if (!check) rmSync(f); }
    }
  }
  // Remove synced skills whose source was deleted. Skills without the marker (e.g. engram) are left alone.
  const dir = join(root, target);
  if (existsSync(dir)) for (const name of readdirSync(dir)) {
    if (!skills.includes(name) && existsSync(join(dir, name, MARK))) { stale.push(`${target}/${name}`); if (!check) rmSync(join(dir, name), { recursive: true }); }
  }
}

// Claude Code agent wrappers
const srcAgents = join(root, '.github/agents');
for (const file of readdirSync(srcAgents).filter((f) => f.endsWith('.agent.md'))) {
  const text = readFileSync(join(srcAgents, file), 'utf8');
  const desc = (text.match(/^description:\s*"?(.*?)"?\s*$/m) || [])[1] || '';
  const tools = /\bagent\b/.test((text.match(/^tools:\s*\[(.*)\]/m) || [])[1] || '')
    ? 'Read, Grep, Glob, Edit, Write, Bash, Agent' : 'Read, Grep, Glob, Edit, Write, Bash';
  const slug = file.replace(/\.agent\.md$/, '');
  put(join(root, '.claude/agents', `${slug}.md`), `---
name: ${slug}
description: "${desc.replace(/"/g, "'")}"
tools: ${tools}
---

<!-- Generated by scripts/agents/sync.mjs. Edit .github/agents/${file} instead. -->

Your full role definition is \`.github/agents/${file}\`. Read it now and follow it exactly; it overrides anything generic here.

Then read \`AGENTS.md\` and load the skills it lists for your role (they are in \`.claude/skills/\`; the source is \`.github/skills/\`).

Before you stop, or whenever you finish a step, update the **Resume here** section of your \`docs/plan/status/<role>.md\` and commit your work (see "Switching AI tools" in AGENTS.md). Then return a short report: what changed (files, branch, PR), the test results, what's blocked, and what you need from which agent.
`);
}

if (check) {
  if (stale.length) { console.error('Out of sync (run node scripts/agents/sync.mjs):\n  ' + stale.join('\n  ')); process.exit(1); }
  console.log('agents and skills in sync');
} else {
  console.log(stale.length ? `updated ${stale.length} file(s)` : 'already in sync');
}
